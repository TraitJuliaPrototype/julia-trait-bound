"""
    ComboCache

Combination caches (the note's rule 4: compiled code for a combination of
packages lives in a package that depends on all of them; an ad-hoc session,
where nothing does, compiles the combination itself). From a session recorded
with `--trace-compile=<file>`, `generate` writes a package that depends on the
project packages that session loaded, with the recorded compilations as its
precompile workload; `build` precompiles it in a background process; `load`
loads the cached combination whose dependencies are all loaded already, so it
brings nothing new into the session, only compiled code. Ordinary Julia
validates that code at load, as for any package image, so the cache is sound
for ordinary code too.

    julia --trace-compile=trace.jl …     # session 1: work as usual
    ComboCache.generate("trace.jl"); ComboCache.build()
    using ComboCache; ComboCache.load()   # session 2, after its `using`s, before the work
"""
module ComboCache

using UUIDs, TOML

"Where generated combination packages live; added to `LOAD_PATH` as a package directory."
cachedir() = get(ENV, "COMBOCACHE_DIR", joinpath(first(DEPOT_PATH), "combocache"))

function _ensure_loadpath()
    d = cachedir()
    mkpath(d)
    d in LOAD_PATH || push!(LOAD_PATH, d)
    return d
end

"""
The active project's direct dependencies that are loaded in this session, in
the order they loaded: the validity of cached code depends on the load order
(code valid when one package loads before another can be invalidated when it
loads after), so the combination package imports them in the session's order.
"""
function loaded_project_order()
    proj = Base.active_project()
    deps = get(TOML.parsefile(proj), "deps", Dict{String,Any}())
    out = String[]
    for m in Base.loaded_modules_order
        n = String(nameof(m))
        haskey(deps, n) && Base.moduleroot(m) === m && !(n in out) && push!(out, n)
    end
    return out
end

"The active project's direct dependencies that are loaded in this session: name => UUID."
function loaded_project_deps()
    proj = Base.active_project()
    deps = get(TOML.parsefile(proj), "deps", Dict{String,Any}())
    out = Dict{String,UUID}()
    for (name, u) in deps
        id = Base.PkgId(UUID(u), name)
        haskey(Base.loaded_modules, id) && (out[name] = UUID(u))
    end
    return out
end

_combo_name(deps) = "Combo_" * string(hash(sort!(collect(keys(deps)))), base = 16)

"""
    generate(tracefile; deps = loaded_project_deps()) -> name

Write a combination package for `deps` whose workload replays the
compilations recorded in `tracefile` (precompile statements). Every loaded
package's name is bound in the generated module, so statements naming types of
transitive dependencies resolve; those naming types of `Main` fail and are
skipped when the package precompiles.
"""
function generate(tracefile::AbstractString; deps = loaded_project_deps(), order = loaded_project_order())
    d = _ensure_loadpath()
    name = _combo_name(deps)
    pdir = joinpath(d, name)
    mkpath(joinpath(pdir, "src"))
    u = uuid5(UUID("2b5f3c1e-7a4d-4e8b-9c0f-1d2e3f4a5b6c"), name)
    proj = Dict{String,Any}("name" => name, "uuid" => string(u), "version" => "0.1.0",
                            "deps" => Dict(k => string(v) for (k, v) in deps))
    open(joinpath(pdir, "Project.toml"), "w") do io
        TOML.print(io, proj)
    end
    stmts = filter(l -> startswith(l, "precompile("), readlines(tracefile))
    unique!(stmts)
    open(joinpath(pdir, "src", name * ".jl"), "w") do io
        println(io, "# generated by ComboCache from ", basename(tracefile), ": ", length(stmts), " recorded compilations")
        println(io, "module ", name)
        for k in [filter(in(keys(deps)), order); sort!(setdiff(collect(keys(deps)), order))]
            println(io, "import ", k)   # in the session's load order
        end
        println(io, "const _STMTS = ", repr(stmts))
        println(io, """
        const _OK = Ref(0)
        if ccall(:jl_generating_output, Cint, ()) == 1
            # the statements name types of every loaded package, transitive dependencies included
            for (id, m) in Base.loaded_modules
                isdefined(@__MODULE__, Symbol(id.name)) || Core.eval(@__MODULE__, :(const \$(Symbol(id.name)) = \$m))
            end
            for s in _STMTS
                try
                    Core.eval(@__MODULE__, Meta.parse(s)) && (_OK[] += 1)
                catch
                end
            end
            @info "\$(nameof(@__MODULE__)): \$(_OK[]) of \$(length(_STMTS)) recorded compilations replayed"
        end
        end""")
    end
    return name
end

"""
    build(name = nothing; project = Base.active_project()) -> Base.Process

Precompile the combination package in a background process (niced), in the
same environment, so that the current session is not slowed down.
"""
function build(name = nothing; project = Base.active_project(), wait::Bool = false)
    d = _ensure_loadpath()
    name === nothing && (name = _combo_name(loaded_project_deps()))
    jl = joinpath(Sys.BINDIR, Base.julia_exename())
    code = "push!(LOAD_PATH, $(repr(d))); Base.require(Base.PkgId(Base.UUID($(repr(_uuid_of(d, name)))), $(repr(name))))"
    cmd = `nice -n 10 $jl --startup-file=no --project=$project -e $code`
    p = run(pipeline(cmd; stdout = joinpath(d, name * ".build.log"), stderr = joinpath(d, name * ".build.log")); wait)
    return p
end
_uuid_of(d, name) = TOML.parsefile(joinpath(d, name, "Project.toml"))["uuid"]

"""
    load() -> Union{Module,Nothing}

Load the cached combination whose dependencies are all loaded in this session
(the largest such), or nothing. Loading it adds no package, only the compiled
code of its image.
"""
function load()
    d = _ensure_loadpath()
    loaded = Set(keys(loaded_project_deps()))
    best = nothing; bestn = -1
    for name in readdir(d)
        isfile(joinpath(d, name, "Project.toml")) || continue
        deps = keys(get(TOML.parsefile(joinpath(d, name, "Project.toml")), "deps", Dict()))
        all(in(loaded), deps) && length(deps) > bestn && (best = name; bestn = length(deps))
    end
    best === nothing && return nothing
    return Base.require(Base.PkgId(Base.UUID(_uuid_of(d, best)), best))
end

end
