# ---------------------------------------------------------------------------
# The error split on stock Julia (design doc, Stage 1). Every call into a
# region op passes a guard that audits the worker's compiled concrete-edge
# closure for piratical targets (ownership.jl). Three session-level modes:
#
#   :warn       (default, the interim rule) name each pirate once, then run
#               on top of it exactly as plain Julia does;
#   :error      poison: the call raises `PiracyError` instead of running;
#   :recompile  the opt-out: plain Julia, no audit at all.
#
# The audit runs at the first call of each (op, representation) and again
# after any world change (any method definition), so whether it fires does
# not depend on precompile workloads, first-call order or load order.
# PoC limits: the audit covers worker closures, not seal code (projection,
# witnesses); a pirate reached only through a dynamic call is applied, as in
# plain Julia (the design accepts this); not thread-safe.
# ---------------------------------------------------------------------------

const MODE = Ref(:warn)
"Set by `verify_main(...; entrypoints = true)`: a trimmed binary, audited at build time; the guard stays off."
const CLOSED_WORLD = Ref(false)
const SESSION = Ref{UInt}(0)

"""
    TraitRegions.mode!(:warn | :error | :recompile)

Set the session-level reaction to piracy against trait-bound code. Also
settable at startup with the environment variable `JULIA_TRAITBOUND`.
"""
function mode!(m::Symbol)
    m in (:warn, :error, :recompile) ||
        throw(ArgumentError("mode must be :warn, :error or :recompile, got :$m"))
    MODE[] = m
    SESSION[] += 2          # every guard re-audits under the new mode
    return m
end

struct PiracyFinding
    method::Method      # the piratical method trait-bound code would call
    sig::Any            # the concrete call signature it intercepts
    caller::Any         # MethodInstance whose compiled code holds the call
end

"""
    PiracyError

Raised (in `:error` mode) when trait-bound code would run on top of a method
defined by a package that owns neither the function nor its argument types.
`catch` blocks inside region ops rethrow it.
"""
struct PiracyError <: Exception
    op::Symbol
    R::Any
    findings::Vector{PiracyFinding}
end

function Base.showerror(io::IO, e::PiracyError)
    print(io, "PiracyError: trait-bound op `", e.op, "` at representation ", e.R,
          " depends on ", length(e.findings) == 1 ? "a method" : "methods",
          " defined by a package that owns neither the function nor its argument types:")
    for f in e.findings
        print(io, "\n  ", f.method, "  [defined by ", owner(f.method.module), "]",
              "\n    intercepts ", f.sig, "\n    called from ", f.caller)
    end
    print(io, "\nRemove the pirate, declare an implementer relation in its Project.toml, ",
          "or opt out with TraitRegions.mode!(:recompile).")
end

"Per-op guard state, one `const` per region op (generated by `@region`)."
mutable struct GuardState
    const op::Symbol
    session::UInt
    world::UInt
    audited::Vector{Any}            # representations audited in this world
    seals::IdDict{Any,Any}          # T => Seal, looked up in this world
    warned::Base.IdSet{Method}      # pirates already reported in :warn mode
end
GuardState(op::Symbol) = GuardState(op, UInt(0), UInt(0), Any[], IdDict{Any,Any}(), Base.IdSet{Method}())

function _restamp!(st::GuardState)
    world = Base.get_world_counter()
    if st.session != SESSION[] || st.world != world
        empty!(st.audited)
        empty!(st.seals)
        st.session = SESSION[]
        st.world = world
    end
    return nothing
end

"""
Seal lookup for entries, cached per op and world. Any method definition bumps
the world and clears the cache, so re-sealing is always seen; the slow path is
a dynamic call, so neither new seals nor other packages' loads can
invalidate the entry.
"""
@inline function _enter(st::GuardState, trait::Type, @nospecialize(t))
    if st.session == SESSION[] && st.world == Base.get_world_counter()
        s = get(st.seals, typeof(t), nothing)
        s === nothing || return s::Seal
    end
    return Base.inferencebarrier(_enter_slow)(st, trait, t)::Seal
end

@noinline function _enter_slow(st::GuardState, trait::Type, @nospecialize(t))
    _restamp!(st)
    s = seal_of(trait, t)
    st.seals[typeof(t)] = s
    return s
end

"Fast path, inlined into every entry: one mode check, two compares, a short scan."
@inline function _guard(st::GuardState, @nospecialize(worker), @nospecialize(w), @nospecialize(r), args...)
    MODE[] === :recompile && return nothing
    R = typeof(r)
    if st.session == SESSION[] && st.world == Base.get_world_counter()
        for x in st.audited
            x === R && return nothing
        end
    end
    # A dynamic call on purpose: the slow path is ordinary code (printing,
    # logging, reflection) whose edges a later package load can invalidate.
    # A static call would hand that exposure to every entry; the design's own
    # rule, applied to its own guard.
    return Base.inferencebarrier(_guard_slow)(st, worker, w, r, args)
end

@noinline function _guard_slow(st::GuardState, @nospecialize(worker), @nospecialize(w), @nospecialize(r), @nospecialize(args::Tuple))
    _restamp!(st)
    R = typeof(r)
    findings = audit(worker, Tuple{typeof(w), R, map(typeof, args)...})
    if isempty(findings)
        push!(st.audited, R)
        return nothing
    end
    MODE[] === :error && throw(PiracyError(st.op, R, findings))   # stays poisoned
    Base.inferencebarrier(_warn_piracy)(st, R, findings)
    push!(st.audited, R)
    return nothing
end

function _warn_piracy(st::GuardState, @nospecialize(R), findings::Vector{PiracyFinding})
    for f in findings
        f.method in st.warned && continue
        push!(st.warned, f.method)
        @warn sprint(showerror, PiracyError(st.op, R, [f])) *
              "\n(warn mode: running on top of the pirate, as plain Julia does)"
    end
    return nothing
end

# --- the audit --------------------------------------------------------------

# CodeInstances whose whole closure was found clean; trusted only while the
# CodeInstance itself is still valid (a pirate intersecting any concrete edge
# below it invalidates it, which removes the trust).
const _CLEAN = Base.IdSet{Core.CodeInstance}()
const _PIRATICAL = IdDict{Method,Bool}()

_piratical(m::Method) = get!(() -> is_piratical(m), _PIRATICAL, m)

_isvalid(ci::Core.CodeInstance, world::UInt) = ci.min_world <= world <= ci.max_world

"Newest native-owner CodeInstance of `mi`, valid or not."
function _latest_ci(mi::Core.MethodInstance)
    isdefined(mi, :cache) || return nothing
    ci = mi.cache
    while true
        ci.owner === nothing && return ci
        isdefined(ci, :next) || return nothing
        ci = ci.next
    end
end

function _valid_ci(mi::Core.MethodInstance, world::UInt)
    isdefined(mi, :cache) || return nothing
    ci = mi.cache
    while true
        ci.owner === nothing && _isvalid(ci, world) && return ci
        isdefined(ci, :next) || return nothing
        ci = ci.next
    end
end

_callee_method(@nospecialize(c)) =
    c isa Core.CodeInstance ? c.def.def :
    c isa Core.MethodInstance ? c.def :
    c isa Method ? c : nothing

function _current_target(@nospecialize(sig), world::UInt)
    m = Base._which(sig; world, raise = false)
    return m === nothing ? nothing : m.method
end

"""
    audit(worker, argtypes) -> Vector{PiracyFinding}

Walk the concrete-edge closure of `worker`'s compiled code at `argtypes` and
report every concrete call whose target is piratical. Valid CodeInstances are
read as recorded; invalidated ones are re-resolved in the current world, so a
pirate that just invalidated the worker is found without recompiling it. If
no code exists yet, the worker is compiled first (the compile-time check).
"""
function audit(@nospecialize(worker), @nospecialize(argtypes); compile::Bool = true)
    world = Base.get_world_counter()
    mi = Base.method_instance(worker, argtypes)
    mi isa Core.MethodInstance || return PiracyFinding[]
    ci = _latest_ci(mi)
    if MODE[] === :error && ci !== nothing && !_isvalid(ci, world)
        # poison without recompiling: re-resolve the invalidated code's edges
        findings = _walk(ci, world)
        isempty(findings) || return findings
    end
    ci = _valid_ci(mi, world)
    if ci === nothing
        compile || return PiracyFinding[]
        # the compile hint directly: generic `precompile` is a function other
        # packages extend (Observables does), which would invalidate the audit
        ccall(:jl_compile_hint, Int32, (Any,), Base.signature_type(worker, argtypes))
        ci = _valid_ci(mi, world)
        ci === nothing && return PiracyFinding[]
    end
    return _walk(ci, world)
end

function _walk(ci0::Core.CodeInstance, world::UInt)
    findings = PiracyFinding[]
    seen = Base.IdSet{Core.CodeInstance}()
    stack = Core.CodeInstance[ci0]
    while !isempty(stack)
        ci = pop!(stack)
        ci in seen && continue
        push!(seen, ci)
        valid = _isvalid(ci, world)
        valid && ci in _CLEAN && continue
        caller = ci.def
        e = ci.edges
        i = 1
        while i <= length(e)
            it = e[i]
            if it isa Int                                   # (n, callsig, callee × n)
                n = abs(it)
                sig = e[i+1]
                for j in 1:n
                    _edge!(findings, stack, sig, e[i+1+j], caller, valid, world)
                end
                i += 2 + n
            elseif it isa Type                              # (sig, MethodTable) or (sig, callee)
                nxt = e[i+1]
                if nxt isa Core.MethodTable
                    _mt_edge!(findings, it, caller, world)
                else
                    _edge!(findings, stack, it, nxt, caller, valid, world)
                end
                i += 2
            elseif it isa Core.CodeInstance || it isa Core.MethodInstance
                mi = it isa Core.CodeInstance ? it.def : it
                _edge!(findings, stack, mi.specTypes, it, caller, valid, world)
                i += 1
            else                                            # bindings, forward-only methods
                i += 1
            end
        end
    end
    if isempty(findings)
        for ci in seen
            _isvalid(ci, world) && push!(_CLEAN, ci)
        end
    end
    return findings
end

function _edge!(findings, stack, @nospecialize(sig), @nospecialize(callee), @nospecialize(caller), valid::Bool, world::UInt)
    if sig isa Type && Base.isdispatchtuple(sig)
        m = valid ? _callee_method(callee) : _current_target(sig, world)
        if m isa Method && _piratical(m)
            push!(findings, PiracyFinding(m, sig, caller))
        end
    end
    if callee isa Core.CodeInstance
        push!(stack, callee)
    elseif callee isa Core.MethodInstance
        c = _latest_ci(callee)
        c === nothing || push!(stack, c)
    end
    return nothing
end

"A concrete call that found no method or an ambiguous one: a pirate that now answers it changes meaning."
function _mt_edge!(findings, @nospecialize(sig), @nospecialize(caller), world::UInt)
    sig isa Type && Base.isdispatchtuple(sig) || return nothing
    m = _current_target(sig, world)
    if m isa Method && _piratical(m)
        push!(findings, PiracyFinding(m, sig, caller))
    end
    return nothing
end

"""
    audit_all() -> Vector{Pair}

Audit every (op, sealed representation) pair that has compiled code, without
calling or compiling anything. Returns `(trait, op, R) => findings` for pairs with
findings. Useful after loading packages at the REPL.
"""
function audit_all()
    out = Pair{Any,Vector{PiracyFinding}}[]
    traits = Base.IdSet{Any}()
    for m in methods(op_info)
        sig = m.sig
        sig isa DataType && length(sig.parameters) == 3 || continue
        Tt = sig.parameters[2]
        Tt isa DataType && Tt <: Type && push!(traits, Tt.parameters[1])
    end
    for trait in traits
        seals = each_seal(trait)
        for (name, entry) in each_op(trait)
            worker, argts = entry[1], entry[2]
            for (_, s) in seals
                all(isconcretetype, argts) || continue
                f = audit(worker, Tuple{typeof(s.w), s.R, argts...}; compile = false)
                isempty(f) || push!(out, (trait, name, s.R) => f)
            end
        end
    end
    return out
end
